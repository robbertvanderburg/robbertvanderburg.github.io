#!/usr/bin/env python3
"""Fetch publications from Semantic Scholar and write them to _data/publications.yml.

This makes the publications list available to Jekyll at *build time*, so the
static HTML served to crawlers already contains the full list — no runtime
API call in the browser is required to see real content.

The author ID is read from _config.yml (author.semantic_scholar); papers listed
under semantic_scholar_exclude are skipped.

Run manually:
    pip install requests pyyaml
    python scripts/fetch_publications.py

Normally this runs on a schedule via .github/workflows/update-publications.yml.
An optional API key in the S2_API_KEY environment variable raises the rate limit.
"""

from __future__ import annotations

import os
import sys
import time
from pathlib import Path

import requests
import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
CONFIG_PATH = REPO_ROOT / "_config.yml"
OUTPUT_PATH = REPO_ROOT / "_data" / "publications.yml"

API_URL = "https://api.semanticscholar.org/graph/v1/author/{author_id}/papers"
FIELDS = "title,authors,year,venue,journal,externalIds,url,openAccessPdf,publicationDate"
MAX_RETRIES = 6


def load_config() -> tuple[str, set[str]]:
    with open(CONFIG_PATH) as f:
        config = yaml.safe_load(f)
    author_id = str((config.get("author") or {}).get("semantic_scholar") or "").strip()
    if not author_id:
        sys.exit("No Semantic Scholar author id set in _config.yml (author.semantic_scholar)")
    exclude = {str(p).strip() for p in config.get("semantic_scholar_exclude") or []}
    return author_id, exclude


def get_with_retry(url: str, params: dict) -> dict:
    # The anonymous API shares one rate limit across all users, so 429s are
    # common; back off and retry before giving up.
    headers = {}
    if os.environ.get("S2_API_KEY"):
        headers["x-api-key"] = os.environ["S2_API_KEY"]
    for attempt in range(MAX_RETRIES + 1):
        resp = requests.get(url, params=params, headers=headers, timeout=30)
        retryable = resp.status_code == 429 or resp.status_code >= 500
        if not retryable or attempt == MAX_RETRIES:
            resp.raise_for_status()
            return resp.json()
        wait = 2 ** attempt
        print(f"Semantic Scholar returned {resp.status_code}; retrying in {wait}s")
        time.sleep(wait)
    raise AssertionError("unreachable")


def fetch_papers(author_id: str) -> list[dict]:
    url = API_URL.format(author_id=author_id)
    params = {"fields": FIELDS, "limit": 100, "offset": 0}
    papers: list[dict] = []
    while True:
        data = get_with_retry(url, params)
        papers.extend(data.get("data") or [])
        if "next" not in data:
            break
        params["offset"] = data["next"]
    return papers


def normalize(paper: dict) -> dict:
    ids = paper.get("externalIds") or {}
    doi = ids.get("DOI") or ""
    arxiv = ids.get("ArXiv") or ""

    authors = ", ".join(a["name"] for a in paper.get("authors") or [] if a.get("name"))

    venue = (
        paper.get("venue")
        or (paper.get("journal") or {}).get("name")
        or ("arXiv preprint" if arxiv else "")
    )

    if doi:
        pub_url = f"https://doi.org/{doi}"
    elif arxiv:
        pub_url = f"https://arxiv.org/abs/{arxiv}"
    else:
        pub_url = paper.get("url") or ""

    oa_pdf = (paper.get("openAccessPdf") or {}).get("url") or ""
    if not oa_pdf and arxiv:
        oa_pdf = f"https://arxiv.org/pdf/{arxiv}"

    return {
        "title": paper.get("title") or "Untitled",
        "year": paper.get("year"),
        "authors": authors,
        "venue": venue,
        "doi": doi,
        "arxiv": arxiv,
        "url": pub_url,
        "oaPdf": oa_pdf,
    }


def main() -> None:
    author_id, exclude = load_config()
    papers = fetch_papers(author_id)
    if not papers:
        # Most likely an API hiccup; keep the existing list rather than wiping it.
        sys.exit("Semantic Scholar returned no papers; leaving publications.yml unchanged")
    papers = [p for p in papers if p.get("paperId") not in exclude]
    # Newest first, with title as tie-breaker so the output is deterministic
    # and the scheduled job only commits when something actually changed.
    papers.sort(
        key=lambda p: (p.get("publicationDate") or str(p.get("year") or ""), p.get("title") or ""),
        reverse=True,
    )
    pubs = [normalize(p) for p in papers]

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(OUTPUT_PATH, "w") as f:
        f.write(
            "# Auto-generated by scripts/fetch_publications.py — do not edit by hand.\n"
            "# Regenerated on a schedule by .github/workflows/update-publications.yml\n"
        )
        yaml.safe_dump(pubs, f, allow_unicode=True, sort_keys=False)

    print(f"Wrote {len(pubs)} publications to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
