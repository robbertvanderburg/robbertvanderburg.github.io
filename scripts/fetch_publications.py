#!/usr/bin/env python3
"""Fetch publications from OpenAlex and write them to _data/publications.yml.

This makes the publications list available to Jekyll at *build time*, so the
static HTML served to crawlers already contains the full list — no runtime
API call in the browser is required to see real content.

Run manually:
    pip install requests pyyaml
    python scripts/fetch_publications.py

Normally this runs on a schedule via .github/workflows/update-publications.yml.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import requests
import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
CONFIG_PATH = REPO_ROOT / "_config.yml"
OUTPUT_PATH = REPO_ROOT / "_data" / "publications.yml"
CONTACT_EMAIL = "r.vander.burg@vu.nl"

ARXIV_RE = re.compile(r"arxiv\.org/abs/(.+)")


def get_author_id() -> str:
    with open(CONFIG_PATH) as f:
        config = yaml.safe_load(f)
    author_id = ((config.get("author") or {}).get("openalex") or "").strip()
    if not author_id:
        sys.exit("No OpenAlex author id set in _config.yml (author.openalex)")
    return author_id


def fetch_works(author_id: str) -> list[dict]:
    url = "https://api.openalex.org/works"
    params = {
        "filter": f"author.id:{author_id}",
        "sort": "publication_year:desc",
        "per_page": 100,
        "mailto": CONTACT_EMAIL,
    }
    works: list[dict] = []
    page = 1
    while True:
        params["page"] = page
        resp = requests.get(url, params=params, timeout=30)
        resp.raise_for_status()
        data = resp.json()
        results = data.get("results", [])
        works.extend(results)
        total = (data.get("meta") or {}).get("count", 0)
        if not results or len(works) >= total:
            break
        page += 1
    return works


def extract_arxiv(work: dict) -> str:
    for loc in work.get("locations") or []:
        landing = loc.get("landing_page_url") or ""
        match = ARXIV_RE.search(landing)
        if match:
            return match.group(1)
    ids = work.get("ids") or {}
    arxiv_id = ids.get("arxiv", "")
    if arxiv_id:
        return arxiv_id.replace("https://arxiv.org/abs/", "")
    return ""


def normalize(work: dict) -> dict:
    title = work.get("title") or "Untitled"
    year = work.get("publication_year")

    authors = ", ".join(
        a["author"]["display_name"]
        for a in (work.get("authorships") or [])
        if a.get("author", {}).get("display_name")
    )

    primary_location = work.get("primary_location") or {}
    venue = (primary_location.get("source") or {}).get("display_name") or ""

    doi_raw = work.get("doi") or ""
    doi = doi_raw.replace("https://doi.org/", "") if doi_raw else ""

    arxiv = extract_arxiv(work)

    if doi:
        pub_url = f"https://doi.org/{doi}"
    elif arxiv:
        pub_url = f"https://arxiv.org/abs/{arxiv}"
    else:
        pub_url = primary_location.get("landing_page_url") or ""

    oa_pdf = (work.get("open_access") or {}).get("oa_url") or ""

    return {
        "title": title,
        "year": year,
        "authors": authors,
        "venue": venue,
        "doi": doi,
        "arxiv": arxiv,
        "url": pub_url,
        "oaPdf": oa_pdf,
    }


def main() -> None:
    author_id = get_author_id()
    works = fetch_works(author_id)
    if not works:
        # Most likely an API hiccup; keep the existing list rather than wiping it.
        sys.exit("OpenAlex returned no works; leaving publications.yml unchanged")
    # Newest first, with title as tie-breaker so the output is deterministic
    # and the scheduled job only commits when something actually changed.
    works.sort(
        key=lambda w: (w.get("publication_date") or "", w.get("title") or ""),
        reverse=True,
    )
    pubs = [normalize(w) for w in works]

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(OUTPUT_PATH, "w") as f:
        f.write(
            "# Auto-generated by scripts/fetch_publications.py — do not edit by hand.\n"
            "# Regenerated on a schedule by .github/workflows/update-publications.yml\n"
        )
        yaml.safe_dump(pubs, f, allow_unicode=True, sort_keys=False)

    print(f"Wrote {len(pubs)} publications to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
